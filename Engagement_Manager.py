"""Engagement Manager: a simulated engagement node for a command & control (C2) network.

Three asyncio loops run concurrently:
  1. receive loop    - ingests (simulated) track updates and records them to disk
  2. operator loop   - validates a track and a resource before creating an engagement
  3. broadcast loop  - serializes system state to JSON for other nodes

All tracks and data are fictional and generated by the simulator.
Records are written as CSV (standard library, no dependencies) or as Parquet
(typed, columnar) when the optional `pyarrow` package is installed.
"""
import argparse
import asyncio
import csv
import json
import logging
import os
from datetime import UTC, datetime
from pathlib import Path

try:  # Parquet support is optional: CSV works with the standard library alone
    import pyarrow as pa
    import pyarrow.parquet as pq
    HAVE_PYARROW = True
except ImportError:  # pragma: no cover - depends on the environment
    HAVE_PYARROW = False

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("Engagement_Manager")

# Output directory: override with the ENGAGEMENT_RECORD_DIR environment variable or --record-dir
DEFAULT_RECORD_DIR = Path(os.environ.get("ENGAGEMENT_RECORD_DIR", "engagement_record"))
DEFAULT_FORMAT = os.environ.get("RECORD_FORMAT", "csv")

FIELDNAMES = ["timestamp", "track_id", "classification", "validity", "position_x", "position_y"]

if HAVE_PYARROW:
    # Typed columns: a real UTC timestamp and floats, instead of CSV's plain text
    PARQUET_SCHEMA = pa.schema([
        ("timestamp", pa.timestamp("us", tz="UTC")),
        ("track_id", pa.string()),
        ("classification", pa.string()),
        ("validity", pa.float64()),
        ("position_x", pa.float64()),
        ("position_y", pa.float64()),
    ])


class EngagementManager:
    def __init__(self, host="127.0.0.1", rx_port=5555, tx_port=5556,
                 record_dir=DEFAULT_RECORD_DIR, record_format=DEFAULT_FORMAT, resources=None):
        self.host = host
        self.rx_port = rx_port  # reserved for the networked version (see README roadmap)
        self.tx_port = tx_port

        self.record_dir = Path(record_dir)
        self.record_dir.mkdir(parents=True, exist_ok=True)

        if record_format not in ("csv", "parquet"):
            raise ValueError(f"record_format must be 'csv' or 'parquet', got {record_format!r}")
        if record_format == "parquet" and not HAVE_PYARROW:
            log.warning("pyarrow is not installed; falling back to CSV records.")
            record_format = "csv"
        self.record_format = record_format

        # State management
        self.active_tracks = {}
        self.resources = dict(resources) if resources else {"interceptors": 10, "support_units": 5}
        self.engagements = {}

    async def start(self):
        """Starts the concurrent receive loop, operator simulation, and state broadcast."""
        log.info("Engagement Manager initializing (records: %s -> %s)", self.record_format, self.record_dir)
        await asyncio.gather(
            self._simulate_receive_stream(),
            self._simulate_operator_action(),
            self._state_broadcast_loop(),
        )

    # ── 1. receive loop ──────────────────────────────────────────────────────
    @staticmethod
    def generate_fake_tracks():
        """Returns one batch of fictional track updates, all stamped with the same UTC time."""
        current_time = datetime.now(UTC).isoformat()
        return [
            {"timestamp": current_time, "track_id": "TRK-101", "classification": "Hostile",
             "validity": 0.95, "position_x": 34.05, "position_y": -118.24},
            {"timestamp": current_time, "track_id": "TRK-102", "classification": "Neutral",
             "validity": 0.88, "position_x": 35.12, "position_y": -118.40},
        ]

    async def _simulate_receive_stream(self, interval=3.0):
        """Simulates receiving a data stream and recording each batch to disk."""
        while True:
            await asyncio.sleep(interval)
            rows = self.generate_fake_tracks()
            self.process_track_batch(rows)
            self.write_records(rows)

    def process_track_batch(self, rows):
        """Updates internal track states from incoming row dictionaries."""
        for row in rows:
            self.active_tracks[row["track_id"]] = {
                "classification": row["classification"],
                "validity": row["validity"],
                "position": (row["position_x"], row["position_y"]),
            }
        log.info("Updated state with %d tracks.", len(rows))

    # ── 2. operator loop ─────────────────────────────────────────────────────
    def engage(self, track_id, resource_type):
        """Validates the track and resource, then creates an engagement.
        Returns the new engagement id, or None if the request is refused."""
        if track_id not in self.active_tracks:
            log.warning("Engagement refused: track %s is not active.", track_id)
            return None
        if self.resources.get(resource_type, 0) <= 0:
            log.warning("Engagement refused: no %s remaining.", resource_type)
            return None

        self.resources[resource_type] -= 1
        engagement_id = f"ENG-{len(self.engagements) + 1}"
        self.engagements[engagement_id] = {
            "track_id": track_id,
            "resource_type": resource_type,
            "status": "Initiated",
            "timestamp": datetime.now(UTC).isoformat(),
        }
        log.info("--- OPERATOR ACTION --- Initiated %s on %s using %s", engagement_id, track_id, resource_type)
        return engagement_id

    async def _simulate_operator_action(self, delay=6.0):
        """Simulates an operator watching the screen and deciding to engage a track."""
        await asyncio.sleep(delay)  # wait for tracks to populate
        self.engage("TRK-101", "interceptors")

    # ── recording ────────────────────────────────────────────────────────────
    def _next_path(self, suffix):
        """Unique UTC-timestamped file name (microseconds, so two writes in one second never collide)."""
        stamp = datetime.now(UTC).strftime("%Y%m%d_%H%M%S_%f")
        return self.record_dir / f"engagement_{stamp}.{suffix}"

    def write_records(self, rows):
        """Writes one batch in the configured format. Returns the file path, or None on failure."""
        try:
            path = self._write_parquet(rows) if self.record_format == "parquet" else self._write_csv(rows)
            log.info("Successfully wrote %s file: %s", self.record_format.upper(), path)
            return path
        except OSError as e:
            log.error("Failed to write records to disk: %s", e)
            return None

    def _write_csv(self, rows):
        path = self._next_path("csv")
        with open(path, mode="w", newline="") as csv_file:
            writer = csv.DictWriter(csv_file, fieldnames=FIELDNAMES)
            writer.writeheader()
            writer.writerows(rows)
        return path

    def _write_parquet(self, rows):
        path = self._next_path("parquet")
        typed = [{**r, "timestamp": datetime.fromisoformat(r["timestamp"])} for r in rows]
        pq.write_table(pa.Table.from_pylist(typed, schema=PARQUET_SCHEMA), str(path))
        return path

    def load_parquet_records(self):
        """Reads every Parquet snapshot in the record directory into one pyarrow Table."""
        if not HAVE_PYARROW:
            raise RuntimeError("pyarrow is required to read Parquet records")
        files = sorted(self.record_dir.glob("*.parquet"))
        if not files:
            return PARQUET_SCHEMA.empty_table()
        return pa.concat_tables([pq.read_table(str(f)) for f in files])

    # ── 3. broadcast loop ────────────────────────────────────────────────────
    def build_state_payload(self):
        """System state as a JSON-serializable dict."""
        return {
            "active_engagements": self.engagements,
            "remaining_resources": self.resources,
            "tracked_objects_count": len(self.active_tracks),
        }

    async def _state_broadcast_loop(self, interval=5.0):
        """Broadcasts active engagements and system state."""
        while True:
            await asyncio.sleep(interval)
            log.info("[BROADCAST] State published -> %s", json.dumps(self.build_state_payload()))


def main(argv=None):
    parser = argparse.ArgumentParser(description="Run the simulated Engagement Manager node.")
    parser.add_argument("--format", choices=["csv", "parquet"], default=DEFAULT_FORMAT,
                        help="record format (parquet needs pyarrow)")
    parser.add_argument("--record-dir", type=Path, default=DEFAULT_RECORD_DIR, help="where snapshots are written")
    args = parser.parse_args(argv)

    manager = EngagementManager(record_dir=args.record_dir, record_format=args.format)
    try:
        asyncio.run(manager.start())
    except KeyboardInterrupt:
        log.info("Engagement Manager shut down by operator.")


if __name__ == "__main__":
    main()
